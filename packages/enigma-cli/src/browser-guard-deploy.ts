/**
 * Where the browser guard (browser-guard.ts) is wired, per agent. Every agent that can refuse a
 * shell command before it runs gets the same `enigma __browser-guard`, and all of them hand it the
 * command the same way (`tool_name` + `tool_input.command` on stdin, exit 2 + stderr to refuse):
 *
 *  - Claude Code: PreToolUse in settings.json, `if`-filtered (browser-guard.ts).
 *  - Kimi Code: a `[[hooks]]` PreToolUse rule in config.toml for its Bash and PowerShell tools.
 *  - Codex: PreToolUse in `hooks.json` beside config.toml. Codex runs a hook only once the user
 *    has trusted it in `/hooks`, by a hash enigma cannot compute, so that one step is theirs.
 *  - OpenCode: an auto-loaded plugin whose `tool.execute.before` throws on a refusal, which
 *    OpenCode returns to the model as the tool's error.
 *
 * Kimi, Codex and OpenCode have no command filter, so the guard runs before every shell command
 * there; the npm launcher answers it under Node (bin/enigma.mjs) instead of starting the binary.
 * The guard is always installed and reads `browserHeadless` when it runs, like Claude's.
 *
 * Only an agent whose config dir already exists is wired: enigma never creates `~/.codex` or
 * `~/.kimi-code` for a tool that is not installed.
 */

import { kimiHome } from "./kimi";
import { dirname, join } from "node:path";
import { enigmaHome, isDir } from "./util";
import { applyKimiHook } from "./kimi-hooks";
import { applyClaudeHook, claudeGlobalSettings } from "./claude-hooks";
import { applyBrowserGuard, BROWSER_GUARD_MARKER } from "./browser-guard";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

/** The command every agent runs; the launcher answers it under Node. */
const COMMAND = `enigma ${BROWSER_GUARD_MARKER}`;

/** Kimi Code's PreToolUse rule over its shell tools (its matcher is a regex on the tool name). */
export function applyKimiBrowserGuard(configPath: string, on: boolean): boolean {
    return applyKimiHook(configPath, BROWSER_GUARD_MARKER, { event: "PreToolUse", matcher: "^(?:Bash|PowerShell)$", command: COMMAND, timeout: 60 }, on) === "changed";
}

/** Codex's PreToolUse group in hooks.json; its shell tool is `Bash` for every command it runs. */
export function applyCodexBrowserGuard(hooksPath: string, on: boolean): boolean {
    const group = { matcher: "^Bash$", hooks: [{ type: "command", command: COMMAND, timeout: 60 }] };
    return applyClaudeHook(hooksPath, "PreToolUse", BROWSER_GUARD_MARKER, group, on) === "changed";
}

/** The plugin file inside an OpenCode config dir. */
function opencodePluginPath(opencodeConfigDir: string): string {
    return join(opencodeConfigDir, "plugins", "enigma-browser-guard.js");
}

/** OpenCode plugin source: hands each shell command and its cwd to the guard and throws its refusal. */
export function opencodeBrowserGuardSource(): string {
    return `// Generated by enigma (browser and push guards). Do not edit; 'enigma config browser-headless off' turns the browser guard off.
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

export const EnigmaBrowserGuard = async (ctx = {}) => ({
    "tool.execute.before": async (input, output) => {
        // OpenCode keeps the id "bash" for every shell it runs (bash, pwsh, cmd).
        if (input.tool !== "bash") return;
        const command = output && output.args && output.args.command;
        if (typeof command !== "string" || command === "") return;
        // The push guard reads the repository the command runs in: the tool's workdir, else the session's.
        const base = typeof ctx.directory === "string" && ctx.directory !== "" ? ctx.directory : process.cwd();
        const workdir = output.args.workdir;
        const cwd = typeof workdir === "string" && workdir !== "" ? resolve(base, workdir) : base;
        let r;
        try {
            // shell:true lets Windows resolve enigma.cmd; windowsHide keeps that shell from flashing a console.
            r = spawnSync("enigma", ["${BROWSER_GUARD_MARKER}"], { input: JSON.stringify({ tool_name: "Bash", tool_input: { command }, cwd }), encoding: "utf8", timeout: 60000, shell: process.platform === "win32", windowsHide: true });
        } catch {
            return;
        }
        if (r.status === 2) throw new Error((r.stderr || "").trim() || "enigma: the command was refused by the browser or push guard.");
    },
});
`;
}

/** Write (on) or remove (off) the OpenCode plugin. Returns true when changed. */
export function applyOpencodeBrowserGuard(opencodeConfigDir: string, on: boolean): boolean {
    const path = opencodePluginPath(opencodeConfigDir);
    const source = opencodeBrowserGuardSource();
    if (!on) {
        if (!existsSync(path)) return false;
        rmSync(path, { force: true });
        return true;
    }
    if (existsSync(path) && readFileSync(path, "utf8") === source) return false;
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, source);
    return true;
}

/** Wire the guard into one agent's global config, when that agent is installed. Returns true when changed. */
export function applyBrowserGuardGlobal(toolName: string): boolean {
    if (toolName === "claude") return applyBrowserGuard(claudeGlobalSettings(), true) === "changed";
    if (toolName === "kimi") return isDir(kimiHome()) && applyKimiBrowserGuard(join(kimiHome(), "config.toml"), true);
    const codex = join(enigmaHome(), ".codex");
    if (toolName === "codex") return isDir(codex) && applyCodexBrowserGuard(join(codex, "hooks.json"), true);
    const opencode = join(enigmaHome(), ".config", "opencode");
    if (toolName === "opencode") return isDir(opencode) && applyOpencodeBrowserGuard(opencode, true);
    return false;
}

/** What to tell the user once Codex has the guard: it runs only after they trust it. */
export const CODEX_TRUST_NOTICE = "Codex: enigma's browser guard is in hooks.json; Codex runs it only after you trust it once with /hooks.";

/** Wire the guard into one managed account's config dir. */
export function mirrorBrowserGuardWiring(toolName: string, accountDir: string): boolean {
    if (!isDir(accountDir)) return false;
    if (toolName === "claude") return existsSync(join(accountDir, "settings.json")) && applyBrowserGuard(join(accountDir, "settings.json"), true) === "changed";
    if (toolName === "kimi") return applyKimiBrowserGuard(join(accountDir, "config.toml"), true);
    if (toolName === "codex") return applyCodexBrowserGuard(join(accountDir, "hooks.json"), true);
    if (toolName === "opencode") return applyOpencodeBrowserGuard(join(accountDir, "xdg-config", "opencode"), true);
    return false;
}
